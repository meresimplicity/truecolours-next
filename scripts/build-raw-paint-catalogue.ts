async function buildCatalogue() {
  const existingPath = path.join(process.cwd(), "data", "raw", "oem-paint-codes.json");
  let existingRecords: any[] = [];
  if (fs.existsSync(existingPath)) {
    existingRecords = JSON.parse(fs.readFileSync(existingPath, "utf-8"));
  }

  const allRecords: any[] = [];

  // Add the 30 Audi A1 Sportback records
  for (const c of audiA1Colours) {
    allRecords.push({
      brand: "Audi",
      manufacturer: "Audi",
      model: "A1 Sportback",
      generation: c.generation,
      yearFrom: c.yearFrom,
      yearTo: c.yearTo,
      years: c.years,
      code: c.primaryCode,
      primaryCode: c.primaryCode,
      salesCodes: c.salesCodes,
      name: c.name,
      finish: c.finish,
      hex: c.swatchHex,
      swatchHex: c.swatchHex,
      swatchSource: c.swatchSource,
      swatchVerified: c.swatchVerified,
      alternativeNames: c.alternativeNames,
      source: c.source,
      sourceUrl: c.sourceUrl,
      sourceLicense: c.sourceLicense,
      verified: c.verified,
      verifiedBy: (c as any).verifiedBy,
      verifiedAt: (c as any).verifiedAt,
    });
  }

  // Convert and add existing records, enriching with multiCode & years array
  for (const r of existingRecords) {
    if (r.brand === "Audi" && r.model === "A1 Sportback") {
      // Already added above with exact reference specifications
      continue;
    }

    const { primaryCode, salesCodes } = parseMultiCode(r.code);
    const yFrom = r.yearFrom || r.year || 2010;
    const yTo = r.yearTo || r.year || 2024;
    const years = r.years || Array.from({ length: yTo - yFrom + 1 }, (_, i) => yFrom + i);

    allRecords.push({
      brand: r.brand,
      manufacturer: r.brand,
      model: r.model,
      generation: r.generation,
      yearFrom: yFrom,
      yearTo: yTo,
      years,
      code: primaryCode || r.code,
      primaryCode: primaryCode || r.code,
      salesCodes,
      name: r.name,
      finish: r.finish || "Solid",
      hex: r.hex,
      swatchHex: r.hex,
      swatchSource: r.hex ? "OEM Formulation Approximation" : undefined,
      swatchVerified: Boolean(r.verified),
      alternativeNames: r.alternativeNames || [
        { language: "en", name: r.name },
      ],
      source: r.source || "open-data",
      sourceUrl: r.sourceUrl || "https://truecolourspaints.co.za/catalogue",
      sourceLicense: "Open Automotive Data Standard",
      verified: Boolean(r.verified),
      notes: r.notes,
      formulaReference: r.formulaReference,
      verifiedBy: r.verifiedBy,
      verifiedAt: r.verifiedAt,
    });
  }

  // Write out comprehensive raw catalogue
  const outPath = path.join(process.cwd(), "data", "raw", "oem-paint-catalogue.json");
  fs.writeFileSync(outPath, JSON.stringify(allRecords, null, 2));
  console.log(`-> Written ${allRecords.length} total raw paint records to data/raw/oem-paint-catalogue.json`);
}

