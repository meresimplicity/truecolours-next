import { NextResponse } from "next/server";
import { withTransaction } from "@/lib/db";

interface ResolveBody {
  keep: "a" | "b";
}

export async function POST(request: Request, { params }: { params: { id: string } }) {
  const body = (await request.json()) as ResolveBody;
  if (body.keep !== "a" && body.keep !== "b") {
    return NextResponse.json({ error: "'keep' must be 'a' or 'b'" }, { status: 400 });
  }

  try {
    await withTransaction(async (client) => {
      const conflictRes = await client.query(
        `select id, paint_color_id, paint_fitment_id, field_name, source_a_value, source_b_value, source_a_id, source_b_id
           from data_conflicts where id = $1 and status = 'open'`,
        [params.id]
      );
      const conflict = conflictRes.rows[0];
      if (!conflict) throw new Error("Conflict not found or already resolved");

      const winningValue = body.keep === "a" ? conflict.source_a_value : conflict.source_b_value;
      const winningSourceId = body.keep === "a" ? conflict.source_a_id : conflict.source_b_id;
      const targetTable = conflict.paint_color_id ? "paint_colors" : "paint_fitments";
      const targetId = conflict.paint_color_id ?? conflict.paint_fitment_id;

      // field_name is trusted admin-facing metadata generated by our own
      // dedupe script (src/scripts/dedupe-paint.ts), never user input —
      // still allow-listed defensively since it's interpolated into SQL.
      const allowedFields = ["name", "hex", "finish", "base_color", "standard_number", "year_from", "year_to", "market"];
      if (!allowedFields.includes(conflict.field_name)) {
        throw new Error(`Refusing to update unrecognized field: ${conflict.field_name}`);
      }

      await client.query(
        `update ${targetTable} set ${conflict.field_name} = $1, verification_status = 'team_verified', updated_at = now() where id = $2`,
        [winningValue, targetId]
      );
      await client.query(
        `update data_conflicts set status = 'resolved', resolved_at = now(),
                resolution_note = 'Admin selected value from source ' || $1
          where id = $2`,
        [winningSourceId, params.id]
      );
    });
  } catch (err) {
    return NextResponse.json({ error: err instanceof Error ? err.message : "Resolve failed" }, { status: 400 });
  }

  return NextResponse.json({ ok: true });
}
